(function () {
  document.addEventListener("DOMContentLoaded", function () {
    if (window.KZT.initNotice) window.KZT.initNotice();
    if (window.KZT.initHeaderToggle) window.KZT.initHeaderToggle();
    if (window.KZT.initCarousel) window.KZT.initCarousel();
    if (window.KZT.initFormHandler) window.KZT.initFormHandler();
    if (window.KZT.initDarkMode) window.KZT.initDarkMode();
    if (window.KZT.initScrollReveal) window.KZT.initScrollReveal();
    if (window.KZT.initSmoothScroll) window.KZT.initSmoothScroll();
  });
})();
